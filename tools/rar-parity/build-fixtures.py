def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "rar-parity-build"})
    with urllib.request.urlopen(req) as r:
        return r.read()


def uudecode(text: bytes) -> bytes:
    out = bytearray()
    started = False
    for line in text.splitlines():
        if line.startswith(b"begin "):
            started = True
            continue
        if not started or line == b"end" or not line:
            continue
        if line[0:1] == b"`":
            continue
        out += binascii.a2b_uu(line)
    return bytes(out)


def stage_libarchive() -> None:
    dst = os.path.join(FX, "libarchive")
    shutil.rmtree(dst, ignore_errors=True)
    os.makedirs(dst)
    tree = json.loads(fetch(LA_TREE))
    names = [t["path"] for t in tree["tree"] if t["path"].startswith("libarchive/test/") and t["path"].endswith(".uu") and "rar" in t["path"].lower()]
    decoded: dict[str, bytes] = {}
    for path in sorted(names):
        base = os.path.basename(path)[:-3]
        data = uudecode(fetch(LA_RAW + path))
        if base.endswith(".Z"):
            data = subprocess.run(["gzip", "-dc"], input=data, capture_output=True, check=True).stdout
            base = base[:-2]
        decoded[base] = data
    consumed = set()
    for out, parts in SPLIT_GROUPS.items():
        decoded[out] = b"".join(decoded[p] for p in parts)
        consumed.update(parts)
    for base, data in decoded.items():
        if base in consumed:
            continue
        with open(os.path.join(dst, base), "wb") as f:
            f.write(data)
    with open(os.path.join(dst, "LICENSE.txt"), "wb") as f:
        f.write(fetch(LA_RAW + "COPYING"))


def stage_derived() -> None:
    dst = os.path.join(FX, "derived")
    shutil.rmtree(dst, ignore_errors=True)
    os.makedirs(dst)
    gen = os.path.join(FX, "generated")

    def read(n: str) -> bytes:
        with open(os.path.join(gen, n), "rb") as f:
            return f.read()

    def write(n: str, data: bytes) -> None:
        with open(os.path.join(dst, n), "wb") as f:
            f.write(data)

    def zip_of(entries: list[tuple[str, bytes]]) -> bytes:
        b = io.BytesIO()
        with zipfile.ZipFile(b, "w", zipfile.ZIP_DEFLATED) as z:
            for n, d in entries:
                zi = zipfile.ZipInfo(n, (2020, 1, 1, 0, 0, 0))
                zi.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(zi, d)
        return b.getvalue()

    inner = {4: read("nest-rar4-depth1.rar"), 5: read("nest-rar5-depth1.rar")}
    zinner = zip_of([("zipinner.txt", b"RARPARITY-MARKER zip-inner\n" * 20)])
    write("nest-zip-in-rar4.rar", rarwrite.rar4_archive([("inner.zip", zinner)]))
    write("nest-zip-in-rar5.rar", rarwrite.rar5_archive([("inner.zip", zinner)]))
    for v in (4, 5):
        write(f"nest-rar{v}-in-zip.zip", zip_of([("inner.rar", inner[v])]))
        write(f"nest-rar{v}-in-zip-in-zip.zip", zip_of([("inner.zip", zip_of([("inner.rar", inner[v])]))]))
        z = zip_of([("inner.rar", inner[v])])
        wrap = rarwrite.rar5_archive if v == 4 else rarwrite.rar4_archive
        write(f"nest-rar{v}-in-zip-in-rar{9 - v}.rar", wrap([("inner.zip", z)]))
        chain = zip_of([("a.rar", wrap([("b.zip", z)]))])
        write(f"nest-rar{v}-zip-rar-zip-rar-chain.zip", zip_of([("c.rar", rarwrite.rar4_archive([("d.zip", chain)]))]))
    deep = zinner
    for i in range(8):
        deep = (rarwrite.rar5_archive if i % 2 else rarwrite.rar4_archive)([(f"l{i}.zip" if i % 2 == 0 else f"l{i}.rar", deep)])
        if i % 2 == 1:
            deep = zip_of([(f"z{i}.rar", deep)])
    write("nest-mixed-13-layers.zip", deep)

    for v in (4, 5):
        for kind in ("compressed", "solid"):
            src = read(f"gen-rar{v}-{kind}.rar")
            tag = f"rar{v}-{kind}"
            write(f"corrupt-{tag}-truncated-half.rar", src[: len(src) // 2])
            write(f"corrupt-{tag}-truncated-endheader.rar", src[:-12])
            mid = bytearray(src)
            mid[len(src) // 2] ^= 0xFF
            write(f"corrupt-{tag}-flipped-data-byte.rar", bytes(mid))
            hdr = bytearray(src)
            hdr[24] ^= 0xFF
            write(f"corrupt-{tag}-flipped-header-byte.rar", bytes(hdr))
    write("corrupt-signature-only-rar4.rar", rarwrite.RAR4_MARKER)
    write("corrupt-signature-only-rar5.rar", rarwrite.RAR5_MARKER)
    write("corrupt-signature-then-garbage.rar", rarwrite.RAR5_MARKER + bytes(range(256)) * 4)
    write("corrupt-rar5-stored-declared-size-too-large.rar", read("gen-rar5-stored.rar")[:200])


def xor_decode(data: bytes) -> bytes:
    return bytes(b ^ XOR_KEY[i % len(XOR_KEY)] for i, b in enumerate(data))


def rar_format(data: bytes) -> str:
    off = data.find(b"Rar!\x1a\x07")
    if off < 0:
        return "not-rar"
    if data[off + 6] == 1:
        return "RAR5"
    versions: set[int] = set()
    pos = off + 7
    try:
        while pos + 7 <= len(data):
            htype, flags, size = struct.unpack("<BHH", data[pos + 2 : pos + 7])
            if size < 7:
                break
            add = struct.unpack("<I", data[pos + 7 : pos + 11])[0] if flags & 0x8000 else 0
            if htype == 0x74:
                versions.add(data[pos + 7 + 4 + 4 + 1 + 4 + 4])
            pos += size + add
    except (struct.error, IndexError):
        pass
    return "RAR4 unp" + "+".join(str(v) for v in sorted(versions)) if versions else "RAR4"


def collect_rows() -> list[dict]:
    rows = []
    for src in ("libarchive", "generated", "derived"):
        d = os.path.join(FX, src)
        for n in sorted(os.listdir(d)):
            if n == "LICENSE.txt":
                continue
            rows.append({"file": f"{src}/{n}", "source": src})
    for p in CLAMAV_XOR:
        rows.append({"file": p, "source": "clamav"})
    return rows


def category(row: dict) -> tuple[str, list[str]]:
    n = os.path.basename(row["file"]).lower()
    tags: list[str] = []
    if any(m in n for m in VOLUME_MARKERS) or "splitted" in n:
        return "multivolume", tags
    if n.startswith("corrupt-"):
        return "corrupt", tags
    if n.startswith("nest-"):
        return "nested", tags
    if n.startswith("bomb-"):
        return "bomb", tags
    if "encrypt" in n or "crypt" in n:
        return "encrypted", tags
    if row["source"] == "libarchive" and any(k in n for k in ("overflow", "bad_", "leftshift", "toolong", "too_small", "underflow", "invalid", "truncated", "use_after_free", "unbound", "desync", "huge", "distance", "loop_bug", "pointer_leak", "out_of_bounds", "unsupported", "noeof", "exceeds", "readtables", "redir", "dict_reference", "nonempty_dir", "seek_data", "skip_block", "block_size", "different", "extra_bytes", "invalid_hash")):
        return "fuzz", tags
    return "valid", tags


def sha256(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def reference_extract(rows: list[dict], unrar_dir: str) -> dict[str, dict]:
    work = tempfile.mkdtemp(prefix="rarparity-")
    indir = os.path.join(work, "in")
    outdir = os.path.join(work, "out")
    os.makedirs(indir)
    os.makedirs(outdir)
    for i, r in enumerate(rows):
        with open(os.path.join(HERE, r["path"] if "path" in r else os.path.join("fixtures", r["file"])) if r["source"] != "clamav" else os.path.join(REPO, r["file"]), "rb") as f:
            data = f.read()
        if r["source"] == "clamav":
            data = xor_decode(data)
        r["_staged"] = f"{i:04d}.rar"
        with open(os.path.join(indir, r["_staged"]), "wb") as f:
            f.write(data)
    script = r"""
export LANG=C.UTF-8 LC_ALL=C.UTF-8
cd /in
for f in *.rar; do
  mkdir -p /out/$f.d
  timeout 120 /r/unrar x -p- -y -idq -o+ -- /in/$f /out/$f.d/ > /out/$f.log 2>&1
  echo $? > /out/$f.rc
done
"""
    subprocess.run(["docker", "run", "--rm", "--platform", "linux/amd64", "-v", f"{unrar_dir}:/r:ro", "-v", f"{indir}:/in:ro", "-v", f"{outdir}:/out", "debian:trixie-slim", "sh", "-c", script], check=True)
    res = {}
    for r in rows:
        s = r["_staged"]
        with open(os.path.join(outdir, s + ".rc")) as f:
            rc = int(f.read().strip())
        with open(os.path.join(outdir, s + ".log"), errors="replace") as f:
            log = f.read()
        files = []
        for dp, _, fns in os.walk(os.path.join(outdir, s + ".d")):
            for fn in fns:
                p = os.path.join(dp, fn)
                if os.path.islink(p) or not os.path.isfile(p):
                    continue
                with open(p, "rb") as fh:
                    d = fh.read()
                if d:
                    files.append({"name": os.path.relpath(p, os.path.join(outdir, s + ".d")), "size": len(d), "sha256": sha256(d), "data": d})
        res[r["file"]] = {"rc": rc, "log": log, "files": files, "zip_members": zip_members(files)}
    shutil.rmtree(work, ignore_errors=True)
    return res


def zip_members(files: list[dict]) -> list[dict]:
    out = []
    for x in files:
        if x["data"][:4] == b"PK\x03\x04":
            try:
                with zipfile.ZipFile(io.BytesIO(x["data"])) as z:
                    for zi in z.infolist():
                        d = z.read(zi)
                        if d:
                            out.append({"name": zi.filename, "size": len(d), "sha256": sha256(d), "data": d})
            except zipfile.BadZipFile:
                pass
    return out


MIN_SCAN_SIZE = 6
MAX_FILESIZE = 100 * 1024 * 1024


def provable_hashes(candidates: dict[str, bytes], image: str) -> set[str]:
    work = tempfile.mkdtemp(prefix="rarparity-val-")
    sigs = os.path.join(work, "sigs")
    files = os.path.join(work, "files")
    os.makedirs(sigs)
    os.makedirs(files)
    with open(os.path.join(sigs, "v.hdb"), "w") as f:
        for h, d in candidates.items():
            f.write(f"{h}:{len(d)}:V.{h}\n")
    for h, d in candidates.items():
        with open(os.path.join(files, h), "wb") as f:
            f.write(d)
    out = subprocess.run(["docker", "run", "--rm", "-v", f"{sigs}:/sigs:ro", "-v", f"{files}:/files:ro", image, "clamscan", "-d", "/sigs", "-r", "--no-summary", "/files"], capture_output=True, text=True)
    found = set()
    for line in out.stdout.splitlines():
        if line.endswith(" FOUND"):
            found.add(os.path.basename(line.split(":")[0]))
    shutil.rmtree(work, ignore_errors=True)
    return found


def sig_name(h: str) -> str:
    return f"RarParity.Content.{h[:16]}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--unrar-dir", required=True)
    ap.add_argument("--skip-fetch", action="store_true")
    ap.add_argument("--validator-image", default="clamav-rar-unrar", help="ClamAV image used to prove which inner files a signature can detect standalone")
    a = ap.parse_args()
    if not a.skip_fetch:
        stage_libarchive()
    stage_derived()
    rows = collect_rows()
    for r in rows:
        r["path"] = os.path.join("fixtures", r["file"]) if r["source"] != "clamav" else r["file"]
    ref = reference_extract(rows, os.path.abspath(a.unrar_dir))

    zip_leaf = b"RARPARITY-MARKER zip-inner\n" * 20
    candidates: dict[str, bytes] = {sha256(zip_leaf): zip_leaf}
    for r in ref.values():
        for x in r["files"] + r["zip_members"]:
            if MIN_SCAN_SIZE <= x["size"] <= MAX_FILESIZE:
                candidates[x["sha256"]] = x["data"]
    provable = provable_hashes(candidates, a.validator_image)
    manifest = []
    hashes: dict[str, tuple[str, int]] = {}
    comment_text = b"Comment text for the archive RARPARITY-COMMENT\n"
    hashes[sha256(comment_text)] = ("comment", len(comment_text))
    marker_leaf = ref["generated/nest-rar4-depth1.rar"]["files"][0]
    leaves = {
        "zip": (sha256(zip_leaf), len(zip_leaf)),
        "marker": (marker_leaf["sha256"], marker_leaf["size"]),
    }

    def add_hash(h: str, size: int) -> str:
        hashes[h] = ("content", size)
        return sig_name(h)

    for r in rows:
        cat, tags = category(r)
        path = os.path.join(REPO, r["file"]) if r["source"] == "clamav" else os.path.join(FX, r["file"])
        with open(path, "rb") as f:
            data = f.read()
        if r["source"] == "clamav":
            data = xor_decode(data)
        fmt = rar_format(data)
        refr = ref[r["file"]]
        base = os.path.basename(r["file"])
        members = [x for x in refr["files"] + refr["zip_members"] if x["sha256"] in provable]
        names = sorted({add_hash(x["sha256"], x["size"]) for x in members})
        oversize = any(x["size"] > MAX_FILESIZE for x in refr["files"])
        log = refr["log"].lower()
        if cat == "multivolume":
            exp = {"kind": "error"}
        elif r["source"] == "derived" and base.startswith("nest-"):
            leaf = leaves["zip"] if base.startswith("nest-zip-in-rar") or "mixed" in base else leaves["marker"]
            exp = {"kind": "detect", "detect": [add_hash(*leaf)]}
        elif refr["rc"] in (0, 10) and "corrupt" in log:
            exp = {"kind": "error"}
        elif refr["rc"] == 0 and oversize:
            exp = {"kind": "limits", "note": "an inner file exceeds the default max-filesize (100M)"}
        elif refr["rc"] in (0, 10) and names:
            exp = {"kind": "detect", "detect": names}
        elif refr["rc"] in (0, 10):
            exp = {"kind": "clean", "note": "no inner file that clamscan detects standalone (empty, under 6 bytes, or a type ClamAV does not hash-match); nothing to prove"}
        elif "password" in log or "encrypt" in log:
            exp = {"kind": "encrypted"}
            if names and "partial" in base:
                if r["source"] == "generated":
                    exp = {"kind": "detect", "detect": names, "note": "some entries encrypted"}
                else:
                    exp = {"kind": "encrypted", "note": "some entries encrypted; both builds report only Heuristics.Encrypted.RAR, the signature of the unencrypted entry never matches"}
        else:
            exp = {"kind": "error"}
        row = {
            "id": r["file"].replace("/", "__"),
            "file": r["file"],
            "category": cat,
            "format": fmt,
            "source": r["source"],
            "origin": ORIGINS[r["source"]],
            "licence": LICENCES[r["source"]],
            "options": [],
            "expected": exp,
            "reference_unrar": {"rc": refr["rc"], "log": " ".join(refr["log"].split())[:160], "files": [x["name"] for x in refr["files"]]},
        }
        manifest.append(row)
        extra = None
        if base in ("nest-rar4-depth6.rar", "nest-rar5-depth6.rar"):
            extra = (["--max-recursion=4"], "max-recursion-4")
        elif base == "nest-mixed-13-layers.zip":
            extra = (["--max-recursion=8"], "max-recursion-8")
        elif base.startswith("bomb-") and base.endswith("high-ratio.rar"):
            extra = (["--max-filesize=1M"], "max-filesize-1M")
        elif base.startswith("bomb-") and base.endswith("many-files.rar"):
            extra = (["--max-files=100"], "max-files-100")
        if extra:
            manifest.append(dict(row, id=row["id"] + "@" + extra[1], category="bomb", options=extra[0], expected={"kind": "limits"}))
    for v in (4, 5):
        manifest.append({"id": f"runtime__large-entry-stored-rar{v}", "file": f"runtime/large-entry-stored-rar{v}", "runtime": f"large-entry-stored-rar{v}", "category": "bomb", "format": f"RAR{v}", "source": "runtime", "origin": "generated at scan time by compare.py (rarwrite.py): one stored 110 MiB entry, above the default max-filesize of 100M", "licence": LICENCES["derived"], "options": [], "expected": {"kind": "limits"}})
        manifest.append({"id": f"runtime__many-files-stored-rar{v}", "file": f"runtime/many-files-stored-rar{v}", "runtime": f"many-files-stored-rar{v}", "category": "bomb", "format": f"RAR{v}", "source": "runtime", "origin": "generated at scan time by compare.py (rarwrite.py): 10100 eight-byte entries, above the default max-files of 10000", "licence": LICENCES["derived"], "options": [], "expected": {"kind": "limits"}})
    json.dump({"libarchive_commit": LIBARCHIVE_SHA, "rows": manifest}, open(os.path.join(HERE, "manifest.json"), "w"), indent=1)
    os.makedirs(os.path.join(HERE, "signatures"), exist_ok=True)
    with open(os.path.join(HERE, "signatures", "rar-parity.hdb"), "w") as f:
        for h, (label, size) in sorted(hashes.items(), key=lambda kv: kv[1][0] + kv[0]):
            f.write(f"{h}:{size}:{'RarParity.Comment' if label == 'comment' else sig_name(h)}\n")


if __name__ == "__main__":
    main()
