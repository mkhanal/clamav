#!/usr/bin/env python3
"""Authoring tool: assembles fixtures/ and writes manifest.json and signatures/.

Not needed to run the comparison (compare.py reads the committed manifest);
rerun it only to regenerate or extend the set. Steps:

  1. fetch libarchive's RAR test archives at a pinned commit and uudecode them
  2. derive nested, truncated and corrupted fixtures from the generated ones
  3. extract every fixture with RARLAB's reference unrar (throwaway container,
     never committed) to learn the true inner content and hash it
  4. write manifest.json (expected outcome per row) and signatures/

Usage: build-fixtures.py --unrar-dir DIR   (DIR holds the linux x64 `unrar` binary)
"""
